// Effective rate (% p.a.) by financing amount, Private Sector promo table.
const PRIVATE_RATE_BANDS = [
  {max: 15000,  rate: 24},
  {max: 50000,  rate: 20},
  {max: 99000,  rate: 17},
  {max: 150000, rate: 14},
];
function privateRateFor(amount){
  const band = PRIVATE_RATE_BANDS.find(b => amount <= b.max) || PRIVATE_RATE_BANDS[PRIVATE_RATE_BANDS.length-1];
  return band.rate;
}

// Reducing-balance annuity, rounded up to the next ringgit like RHB's tables.
function rhbAnnuity(P, annualRatePct, months){
  const r = annualRatePct/1200;
  return P*r/(1-Math.pow(1+r,-months));
}

// Civil table lookup. Amounts between rows use the next RM1,000 row up (so the
// estimate never understates the deduction).
function civilTableInstalment(amount, tenureYears){
  const col = CIVIL_TABLE_TENURES.indexOf(tenureYears);
  if (col === -1) return null;
  const idx = Math.ceil((amount - CIVIL_TABLE_MIN) / CIVIL_TABLE_STEP);
  const row = CIVIL_TABLE[Math.min(Math.max(idx,0), CIVIL_TABLE.length-1)];
  return row[col];
}

// Collection-fee multiplier implied by the civil table (5% annuity vs table,
// ~1.0153 across all large amounts). Used to estimate the 6.5% State/GLC band.
const CIVIL_COLLECTION_FACTOR = 1.0153;

// Returns {instalment, rate, rateLabel} for one product variant.
// variant: 'awam-persekutuan' | 'awam-negeri' | 'pesara' | 'swasta'
function rhbInstalment(variant, amount, tenureYears){
  const months = Math.round(tenureYears*12);
  if (variant === 'awam-persekutuan'){
    return {instalment: civilTableInstalment(amount, tenureYears), rate: 5.00,
      rateLabel: '5.00% p.a. (SBR ' + RHB_SBR.toFixed(2) + '% + 2.25%)'};
  }
  if (variant === 'awam-negeri'){
    const m = rhbAnnuity(amount, 6.5, months) * CIVIL_COLLECTION_FACTOR;
    return {instalment: Math.ceil(m*100)/100, rate: 6.50, rateLabel: '6.50% p.a.'};
  }
  if (variant === 'pesara'){
    return {instalment: Math.ceil(rhbAnnuity(amount, 7.15, months)), rate: 7.15, rateLabel: '7.15% p.a.'};
  }
  const rate = privateRateFor(amount);
  return {instalment: Math.ceil(rhbAnnuity(amount, rate, months)), rate, rateLabel: rate.toFixed(2) + '% p.a.'};
}
